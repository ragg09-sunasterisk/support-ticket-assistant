// Part 9: the one-shot vs loop comparison table (evals/loop-vs-one-shot.md) from the per-issue outcomes
// that `npm run loop-compare` logs. Pure: no files, no Claude.

export type Arm = "one-shot" | "loop";

/** One issue in one arm: a line of logs/part-09-loop-compare.jsonl with `kind: "outcome"`. */
export interface IssueOutcome {
  kind: "outcome";
  run_id: string;
  arm: Arm;
  base: string;
  issue: string;
  /** The hidden check passed AND the verifier was green (npm run check, no protected path). */
  resolved: boolean;
  green: boolean;
  hidden_check: boolean | null;
  worker_calls: number;
  turns: number;
  cost_usd: number;
  /** Worker calls with no `total_cost_usd` (crashed): not in cost_usd. */
  cost_missing: number;
  wall_ms: number;
  /** The loop's last stop rule for the issue; for one-shot, the rule the loop would have applied. */
  stop_rule: string | null;
  status: string;
  transcript_mentions_issue_checks: boolean;
  changed_files: string[];
}

/** The latest run of each arm (by run_id), one outcome per issue. */
export function latestOutcomes(rows: IssueOutcome[]): IssueOutcome[] {
  const latest = new Map<Arm, string>();
  for (const r of rows) if ((latest.get(r.arm) ?? "") < r.run_id) latest.set(r.arm, r.run_id);
  return rows.filter((r) => latest.get(r.arm) === r.run_id);
}

const usd = (n: number) => `$${n.toFixed(2)}`;
const minutes = (ms: number) => `${(ms / 60_000).toFixed(1)} min`;

export interface ArmTotals { issues: number; resolved: number; turns: number; cost: number; missing: number; wallMs: number; calls: number }

export function totals(rows: IssueOutcome[]): ArmTotals {
  return {
    issues: rows.length,
    resolved: rows.filter((r) => r.resolved).length,
    turns: rows.reduce((n, r) => n + r.turns, 0),
    cost: rows.reduce((n, r) => n + r.cost_usd, 0),
    missing: rows.reduce((n, r) => n + r.cost_missing, 0),
    wallMs: rows.reduce((n, r) => n + r.wall_ms, 0),
    calls: rows.reduce((n, r) => n + r.worker_calls, 0),
  };
}

export function compareMarkdown(rows: IssueOutcome[], generatedAt: string): string {
  const issues = [...new Set(rows.map((r) => r.issue))].sort();
  const get = (arm: Arm, issue: string) => rows.find((r) => r.arm === arm && r.issue === issue);
  const cell = (r: IssueOutcome | undefined) =>
    r ? `${r.resolved ? "**yes**" : "no"} | ${r.worker_calls} | ${r.turns} | ${usd(r.cost_usd)}${r.cost_missing ? ` (+${r.cost_missing} no cost)` : ""} | ${minutes(r.wall_ms)} | ${r.stop_rule ?? "–"}`
      : "not run | | | | | ";
  const base = rows[0]?.base ?? "?";
  const lines = [
    "# One-shot `claude -p` vs the issue-fixing loop (Part 9)",
    "",
    `Generated by \`npm run loop-compare\` at ${generatedAt}. Both arms start from commit \`${base.slice(0, 9)}\`, each`,
    "worker in a throwaway worktree without `scripts/issue-checks/`, with the same prompt, flags and 30-turn limit.",
    "One-shot: one call per issue, no retry, no verifier feedback. Loop: `npm run fix-issues`'s controller on all",
    "10 issues (auto-fix on all), retries with the verifier's evidence, every stop rule on.",
    "**Resolved** = the issue's hidden check passes **and** `npm run check` is green with no protected path touched.",
    "Cost is `total_cost_usd` from the stream: an estimate on a Team seat, not a bill. Time is wall time per issue",
    "(worker plus verifier).",
    "",
    "| Issue | One-shot resolved | calls | turns | est. cost | time | rule the loop would apply | Loop resolved | calls | turns | est. cost | time | loop stop |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ...issues.map((id) => `| ${id} | ${cell(get("one-shot", id))} | ${cell(get("loop", id))} |`),
    "",
    "| Arm | Resolved | Worker calls | Turns | Est. cost | Wall time |",
    "|---|---|---|---|---|---|",
  ];
  for (const arm of ["one-shot", "loop"] as Arm[]) {
    const armRows = rows.filter((r) => r.arm === arm);
    if (armRows.length === 0) continue;
    const t = totals(armRows);
    const pct = ((t.resolved / t.issues) * 100).toFixed(0);
    lines.push(`| ${arm} | ${t.resolved}/${t.issues} (${pct}%) | ${t.calls} | ${t.turns} | ${usd(t.cost)}${t.missing ? ` (+${t.missing} calls without cost)` : ""} | ${minutes(t.wallMs)} |`);
  }
  const flagged = rows.filter((r) => r.transcript_mentions_issue_checks);
  lines.push("", "Worker transcripts that mention `issue-checks`: " +
    (flagged.length === 0 ? "none." : flagged.map((r) => `${r.arm} ${r.issue}`).join(", ") + " (reported, not hidden: read those transcripts)."));
  return `${lines.join("\n")}\n`;
}
