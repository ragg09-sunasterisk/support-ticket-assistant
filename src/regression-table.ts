// Builds evals/regression-table.md from per-case eval rows: counts per prompt version and set, and
// the per-case held-out changes between two prompt versions. Pure: no file or model access.
import type { TicketTriage } from "./ticket-triage-schema.ts";
import { JUDGE_ERROR, METRICS } from "./triage-graders.ts";

export type Metric = (typeof METRICS)[keyof typeof METRICS];

export interface EvalRow {
  set: string;
  promptVersion: string;
  ticketId: string;
  caseType: string;
  expected: { category: string; severity: string };
  triage: TicketTriage | null;
  graders: Record<Metric, { pass: boolean; reason: string }>;
}

const COLUMNS: [Metric, string][] = [
  [METRICS.schema, "Schema valid"],
  [METRICS.category, "Category correct"],
  [METRICS.severity, "Severity correct"],
  [METRICS.escalation, "Escalation pass"],
];

// Wrong category or severity with confidence 0.9 or more: the v1 calibration problem.
export function isConfidentMiss(row: EvalRow): boolean {
  const wrong = !row.graders[METRICS.category].pass || !row.graders[METRICS.severity].pass;
  return wrong && row.triage !== null && row.triage.confidence >= 0.9;
}

function describe(row: EvalRow | undefined): string {
  if (!row) return "not run";
  if (!row.triage) return "no valid triage";
  const { category, severity, confidence, escalation_reason } = row.triage;
  return `${category}/${severity} (${confidence}), escalation ${escalation_reason === null ? "null" : "set"}`;
}

export function describeChange(before: EvalRow | undefined, after: EvalRow | undefined): string {
  if (!before || !after) return "missing a run";
  const flips = COLUMNS.filter(([metric]) => before.graders[metric].pass !== after.graders[metric].pass).map(
    ([metric, label]) => `${label.split(" ")[0]!.toLowerCase()} ${after.graders[metric].pass ? "fixed" : "broke"}`,
  );
  if (flips.length > 0) return flips.join(", ");
  return describe(before) === describe(after) ? "no change" : "output changed, same scores";
}

export function buildRegressionTable(rows: EvalRow[], versions: [string, string], generatedAt: string): string {
  const sets = [...new Set(rows.map((r) => r.set))];
  const lines = [
    `# Regression table: ${versions[0]} vs ${versions[1]}`,
    "",
    `Generated by \`npm run eval\` at ${generatedAt}. Code graders: schema, category, severity.`,
    "Model grader: llm-rubric on escalation_reason, judged by `claude -p` on the Team seat.",
    "",
    `| Prompt | Set | Cases | ${COLUMNS.map(([, label]) => label).join(" | ")} | Confident misses |`,
    `|---|---|---|${COLUMNS.map(() => "---|").join("")}---|`,
  ];
  for (const version of versions) {
    for (const set of sets) {
      const group = rows.filter((r) => r.promptVersion === version && r.set === set);
      const counts = COLUMNS.map(([metric]) => `${group.filter((r) => r.graders[metric].pass).length}/${group.length}`);
      // A judge that crashed is not a wrong escalation: say how many fails are grader errors.
      const judgeErrors = group.filter((r) => r.graders[METRICS.escalation].reason.includes(JUDGE_ERROR)).length;
      if (judgeErrors > 0) counts[3] += ` (${judgeErrors} grader errors)`;
      lines.push(`| ${version} | ${set} | ${group.length} | ${counts.join(" | ")} | ${group.filter(isConfidentMiss).length} |`);
    }
  }

  lines.push(
    "",
    "Confident misses: wrong category or severity with confidence 0.9 or more.",
    "",
    `## Held-out changes, ${versions[0]} → ${versions[1]}`,
    "",
    `| Ticket | Type | Expected | ${versions[0]} | ${versions[1]} | Change |`,
    "|---|---|---|---|---|---|",
  );
  const heldOut = rows
    .filter((r) => r.set === "held-out" && r.promptVersion === versions[1])
    .sort((a, b) => a.ticketId.localeCompare(b.ticketId)); // promptfoo returns rows in finish order
  for (const after of heldOut) {
    const before = rows.find((r) => r.set === "held-out" && r.promptVersion === versions[0] && r.ticketId === after.ticketId);
    const { category, severity } = after.expected;
    lines.push(
      `| ${after.ticketId} | ${after.caseType} | ${category}/${severity} | ${describe(before)} | ${describe(after)} | ${describeChange(before, after)} |`,
    );
  }
  return lines.join("\n") + "\n";
}
